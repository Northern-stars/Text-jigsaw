"""Evaluate visual-only, text-only, and visual-plus-text panel ordering.

The three manifests should contain the same sequence IDs. Visual-only images
must be generated by the dataset preprocessing pipeline with embedded text
masked; this runner never silently claims that unmasked images are visual-only.
"""

from __future__ import annotations
# Resolve the project config package when this file is run directly.
import sys as _cli_sys
from pathlib import Path as _CliPath
_cli_root = next((p for p in _CliPath(__file__).resolve().parents if (p / "config" / "cli.py").is_file()), None)
if _cli_root is not None and str(_cli_root) not in _cli_sys.path:
    _cli_sys.path.insert(0, str(_cli_root))
from config.cli import parse_args_with_config

import argparse
import json
import sys
from pathlib import Path

import torch

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from Solver.agent.vlm_ordering_solver import build_ordering_messages
from experiment.eval_utils import add_model_args, build_solver, load_dataset, run_condition, snapshot_checkpoint
from experiment.run_logger import ExperimentLogger


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--visual-manifest", type=Path, required=True, help="Manifest with OCR-masked panel images")
    parser.add_argument("--text-manifest", type=Path, required=True, help="Manifest whose dialog_texts are used")
    parser.add_argument("--multimodal-manifest", type=Path, required=True)
    parser.add_argument("--split", default="test", choices=("val", "test"))
    add_model_args(parser)
    return parse_args_with_config(parser, script_file=__file__)


def main() -> None:
    args = parse_args()
    if args.batch_size != 1:
        raise ValueError("RQ3 currently requires --batch-size 1 so paired records remain unambiguous")
    torch.manual_seed(0)
    solver = build_solver(args)
    run_dir = args.run_root / args.run_id
    config = {key: (str(value) if isinstance(value, Path) else value) for key, value in vars(args).items()}
    config["experiment"] = "RQ3_evidence_modalities"
    config["task"] = "order_remaining_given_first"
    config["layout_blind_protocol"] = True
    config["visual_only_requires_masked_manifest"] = True
    config.update(snapshot_checkpoint(args.checkpoint, run_dir))
    logger = ExperimentLogger(run_dir, config)
    conditions = {
        "visual_only": (args.visual_manifest, True, False),
        "text_only": (args.text_manifest, False, True),
        "visual_text": (args.multimodal_manifest, True, True),
    }
    results = {}
    sequence_sets = {}
    datasets = {}
    for condition, (manifest, include_images, include_text) in conditions.items():
        dataset = load_dataset(manifest, args.split, args)
        if not len(dataset):
            raise ValueError(f"{condition} manifest has no {args.split} samples")
        ids = [sample.sequence_id for sample in dataset.samples]
        if len(ids) != len(set(ids)):
            raise ValueError(f"{condition} manifest contains duplicate sequence IDs")
        sequence_sets[condition] = set(ids)
        datasets[condition] = dataset
    if len({frozenset(ids) for ids in sequence_sets.values()}) != 1:
        raise ValueError("RQ3 modality manifests must have identical sequence IDs for paired comparison")
    for condition, (_, include_images, include_text) in conditions.items():
        dataset = datasets[condition]
        prompt_factory = lambda panels, texts, images=include_images: build_ordering_messages(
            panels, texts, start_index=solver.start_index, include_images=images,
            no_image_note="No panel images are provided; use only the supplied panel text." if not images else None,
        )
        result = run_condition(
            solver, dataset, args, logger, condition=condition,
            prompt_factory=prompt_factory, include_images=include_images, include_text=include_text,
        )
        results[condition] = result
        logger.log(f"condition={condition} split={args.split} exact={result['exact_match']:.4f} pairwise={result['pairwise_accuracy']:.4f} valid={result['valid_output']:.4f}")
    logger.log_metrics({"type": "final", "experiment": "RQ3", "split": args.split, "results": results})
    (run_dir / "rq3_results.json").write_text(json.dumps(results, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
